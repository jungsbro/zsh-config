#!/bin/bash

# vim ==========================================================================
if [[ $(cat /etc/*-release 2> /dev/null | grep -i "archlinux") ]]; then
    # --------------------------------------------------------------------------
    alias vi='/usr/bin/vim'
    alias vim='/usr/bin/vim'
    # --------------------------------------------------------------------------

elif [[ $(cat /etc/*-release 2> /dev/null | grep -i "debian.org") ]] || \
    [[ $(cat /etc/*-release 2> /dev/null | grep -i "ubuntu") ]]; then
    # --------------------------------------------------------------------------
    alias vi='/usr/bin/vim'
    alias vim='/usr/bin/vim'
    # --------------------------------------------------------------------------

elif [[ $(cat /etc/*-release 2> /dev/null | grep -i "centos") ]] || \
    [[ $(cat /etc/*-release 2> /dev/null | grep -i "rocky") ]] || \
    [[ $(cat /etc/*-release 2> /dev/null | grep -i "fedora") ]]; then
    # --------------------------------------------------------------------------
    alias vi='/usr/bin/vimx'
    alias vim='/usr/bin/vimx'
    # --------------------------------------------------------------------------
fi
# ==============================================================================


