#!/bin/bash

# nala =========================================================================
if [[ $(cat /etc/*-release 2> /dev/null | grep -i "debian.org") ]] || \
    [[ $(cat /etc/*-release 2> /dev/null | grep -i "ubuntu") ]]; then
    # --------------------------------------------------------------------------
    apt() {
        command nala "$@"
    }

    sudo() {
        if [ "$1" = "apt" ]; then
            shift
            command sudo nala "$@"
        else
            command sudo "$@"
        fi
    }
    # --------------------------------------------------------------------------
fi
# ==============================================================================
